"""The generated ``taxonomy_translations.py``: category code to locale to ``(name, description)``, as a Python literal."""

from __future__ import annotations

import ast
import json
from collections.abc import Mapping
from pathlib import Path
from typing import Final, TypeAlias

Labels: TypeAlias = dict[str, dict[str, tuple[str, str]]]
"""Category code to locale to ``(name, description)``."""

VARIABLE: Final = "TAXONOMY_TRANSLATIONS"
HEADER: Final = '''"""Machine-translated category names and descriptions, merged in by ``seed_taxonomy``.

They land in ``name_i18n`` and ``description_i18n``. Generated by ``python -m discovery_ingest i18n translate-ui``;
do not edit by hand. The frozen category contract keeps only ``de`` and ``en``. A locale is served only after its
review is recorded in ``seed_data/translations/review.json``.
"""

from __future__ import annotations

'''


def _literal(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def _entry(locale: str, name: str, description: str) -> str:
    return f"        {_literal(locale)}: (\n            {_literal(name)},\n            {_literal(description)},\n        ),\n"


def _category(code: str, locales: Mapping[str, tuple[str, str]]) -> str:
    entries = "".join(_entry(locale, *locales[locale]) for locale in sorted(locales))
    return f"    {_literal(code)}: {{\n{entries}    }},\n"


def render(labels: Labels) -> str:
    """Return the module text for ``labels``: sorted, every tuple exploded, stable across runs."""
    body = "".join(_category(code, labels[code]) for code in sorted(labels))
    opening = f"{VARIABLE}: dict[str, dict[str, tuple[str, str]]] = {{\n"
    return (
        f"{HEADER}{opening}{body}}}\n"
        if labels
        else f"{HEADER}{VARIABLE}: dict[str, dict[str, tuple[str, str]]] = {{}}\n"
    )


def parse(text: str) -> Labels:
    """Return the labels of a module made by :func:`render`; text without the variable gives an empty mapping."""
    for node in ast.parse(text).body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.target.id == VARIABLE:
            return ast.literal_eval(node.value) if node.value else {}
    return {}


def read(path: Path) -> Labels:
    """Return the labels in the module at ``path``; a missing file has none."""
    return parse(path.read_text(encoding="utf-8")) if path.is_file() else {}
